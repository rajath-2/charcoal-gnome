// Builds the top bar stylesheet from preferences. Pure: also imported by tests.
const hexRgb = hex => /^#[0-9a-f]{6}$/i.test(hex)
    ? [1, 3, 5].map(i => parseInt(hex.slice(i, i + 2), 16)) : [128, 128, 128];
export const rgb01 = hex => hexRgb(hex).map(v => v / 255);
const rgba = (hex, alpha) => `rgba(${hexRgb(hex).join(',')},${+alpha.toFixed(3)})`;
// Popup sub-surfaces are the popup color raised by a fixed step, as in the original charcoal set.
const lift = (hex, step) => `#${hexRgb(hex).map(v => Math.min(255, v + step).toString(16).padStart(2, '0')).join('')}`;

export function buildCss(o) {
    const radius = o['corner-radius'], pr = o['popup-radius'];
    const tr = Math.round(pr * 14 / 22), mr = Math.round(pr * 16 / 22);
    const text = o['text-color'], accent = o['accent-color'], bar = o['bar-color'], pop = o['popup-color'];
    const ptext = o['popup-text-color'];
    const line = (width, color, opacity) => width > 0 ? `${width}px solid ${rgba(color, opacity / 100)}` : 'none';
    const border = line(o['border-width'], o['border-color'], o['border-opacity']);
    const popBorder = line(o['popup-border-width'], o['popup-border-color'], o['popup-border-opacity']);
    const barShadow = o.shadow && o['shadow-size'] > 0
        ? `0 ${Math.round(o['shadow-size'] / 3)}px ${o['shadow-size']}px ${rgba(o['shadow-color'], o['shadow-opacity'] / 100)}` : 'none';
    const popShadow = o.shadow && o['popup-shadow-size'] > 0
        ? `0 ${Math.round(o['popup-shadow-size'] / 3)}px ${o['popup-shadow-size']}px 0 ${rgba(o['popup-shadow-color'], o['popup-shadow-opacity'] / 100)}` : 'none';
    const shadow = s => o.shadow ? s : 'none';
    const vert = `${o['top-margin']}px`, height = `${o['bar-height']}px`;
    return `/* Generated by Charcoal Topbar from its preferences. */
#panelBox { background-color: transparent; padding: 0; box-shadow: none; }

/* Compact: one floating bar. Keep the parent unpadded: Blur My Shell positions from panel coordinates. */
#panel.charcoal-compact {
    margin: ${vert} ${o['side-margin']}px ${vert};
    height: ${height};
    background-color: ${rgba(bar, o['bar-opacity'] / 100)};
    background-image: none;
    border: ${border};
    border-radius: ${radius}px;
    box-shadow: ${barShadow};
}
#panel.charcoal-compact #panelLeft { margin-left: 8px; }
#panel.charcoal-compact #panelRight { margin-right: 8px; }

/* Islands: three floating groups. */
#panel.charcoal-islands {
    margin: ${vert} ${o['island-margin']}px ${vert};
    height: ${height};
    background-color: transparent; background-image: none;
    border: none; border-radius: 0; box-shadow: none;
}
#panel.charcoal-islands #panelLeft,
#panel.charcoal-islands #panelCenter,
#panel.charcoal-islands #panelRight {
    background-color: ${rgba(bar, o['islands-opacity'] / 100)};
    border: ${border};
    border-radius: ${radius}px;
    box-shadow: ${barShadow};
    padding: 0 4px;
}

/* Auto: morph.js paints the surface; controls keep the island layout. */
#panel.adaptive-smoke {
    margin: ${vert} ${o['island-margin']}px ${vert};
    height: ${height};
    background-color: transparent; background-image: none;
    border: none; border-radius: 0; box-shadow: none;
    transition-duration: 0ms;
}
#panel.adaptive-smoke #panelLeft,
#panel.adaptive-smoke #panelCenter,
#panel.adaptive-smoke #panelRight {
    background-color: transparent;
    border: 1px solid transparent;
    border-radius: ${radius}px;
    box-shadow: none;
    padding: 0 4px; margin: 0;
    transition-duration: 0ms;
}

/* Bar controls */
#panel {
    color: ${text};
    font-weight: ${o['bold-text'] ? 600 : 400};
    font-size: ${+(o['text-size'] / 100).toFixed(2)}em;
}
#panel .workspace-dot { background-color: ${text} !important; }
#panel .panel-button {
    border-radius: ${radius}px;
    -natural-hpadding: 10px;
    -minimum-hpadding: 5px;
}
#panel .panel-button:hover, #panel .panel-button:focus,
#panel .panel-button.clock-display:hover .clock,
#panel .panel-button.clock-display:focus .clock {
    box-shadow: inset 0 0 0 100px ${rgba(text, 0.09)};
}
#panel .panel-button:active, #panel .panel-button:checked,
#panel .panel-button.clock-display:checked .clock {
    box-shadow: inset 0 0 0 100px ${rgba(accent, 0.18)};
}
#panel .panel-button.clock-display .clock {
    border-radius: ${radius}px;
    padding-left: 10px; padding-right: 10px;
}

/* Popups. Translucent surfaces let Blur My Shell supply the actual blur. */
.popup-menu-content, .quick-settings, .datemenu-popover {
    background-color: ${rgba(pop, o['popup-opacity'] / 100)};
    color: ${ptext};
    border: ${popBorder};
    border-radius: ${pr}px;
    box-shadow: ${popShadow};
}
.quick-settings { padding: 18px; }
.quick-settings-grid { spacing-rows: 10px; spacing-columns: 10px; }
.quick-settings .quick-toggle, .quick-settings .quick-toggle-has-menu { border-radius: ${tr}px; }
.quick-settings .quick-toggle-has-menu .quick-toggle:ltr { border-radius: ${tr}px 0 0 ${tr}px; }
.quick-settings .quick-toggle-has-menu .quick-toggle:rtl { border-radius: 0 ${tr}px ${tr}px 0; }
.quick-settings .quick-toggle-has-menu .quick-toggle:last-child { border-radius: ${tr}px; }
.quick-settings .quick-toggle-has-menu .quick-toggle-menu-button:ltr { border-radius: 0 ${tr}px ${tr}px 0; }
.quick-settings .quick-toggle-has-menu .quick-toggle-menu-button:rtl { border-radius: ${tr}px 0 0 ${tr}px; }
.quick-settings .quick-toggle,
.quick-settings .quick-toggle-has-menu .quick-toggle-menu-button {
    background-color: ${lift(pop, 30)};
    color: ${ptext};
}
.quick-settings .quick-toggle:hover,
.quick-settings .quick-toggle-has-menu .quick-toggle-menu-button:hover { background-color: ${lift(pop, 45)}; }
.quick-settings .quick-toggle:checked,
.quick-settings .quick-toggle-has-menu .quick-toggle-menu-button:checked,
.quick-settings .quick-toggle:checked:hover,
.quick-settings .quick-toggle-has-menu .quick-toggle-menu-button:checked:hover {
    background-color: ${accent};
    color: #171717;
}
.quick-settings .quick-toggle:insensitive,
.quick-settings .quick-toggle-has-menu .quick-toggle-menu-button:insensitive {
    background-color: ${lift(pop, 21)};
    color: ${rgba(ptext, 0.55)};
}
.quick-settings .quick-toggle:focus,
.quick-settings .quick-toggle-has-menu .quick-toggle-menu-button:focus {
    box-shadow: inset 0 0 0 2px ${ptext} !important;
}
.quick-settings .quick-toggle-has-menu:checked .quick-toggle-separator { background-color: ${rgba(pop, 0.22)}; }
.quick-toggle-menu {
    background-color: ${rgba(lift(pop, 10), Math.min(1, o['popup-opacity'] / 100 + 0.08))};
    border: 1px solid ${rgba(ptext, 0.09)};
    border-radius: ${mr}px;
}
.quick-toggle-menu .header .icon.active { background-color: ${accent}; color: #171717; }
.quick-settings .slider {
    color: ${ptext};
    -barlevel-height: 6px;
    -barlevel-background-color: ${lift(pop, 48)};
    -barlevel-active-background-color: ${accent};
    -slider-handle-radius: 7px;
}
.datemenu-popover { padding: 12px; }
.datemenu-calendar-column { spacing: 10px; }
.datemenu-popover .calendar,
.datemenu-popover .events-button,
.datemenu-popover .world-clocks-button,
.datemenu-popover .weather-button {
    background-color: ${rgba(ptext, 0.045)};
    border-radius: ${mr}px;
}
.datemenu-popover .calendar .calendar-day.calendar-today { background-color: ${accent}; color: #171717 !important; }
.datemenu-popover .message, .notification-banner {
    background-color: ${rgba(lift(pop, 16), 0.94)};
    color: ${ptext};
    border: 1px solid ${rgba(ptext, 0.10)};
    border-radius: ${mr}px;
}
.datemenu-popover .message:hover, .notification-banner:hover { background-color: ${rgba(lift(pop, 25), 0.97)}; }
.datemenu-popover .message:second-in-stack { background-color: ${lift(pop, 18)}; }
.datemenu-popover .message:lower-in-stack { background-color: ${lift(pop, 14)}; }
.datemenu-popover .message .message-header,
.notification-banner .message-header { color: ${rgba(ptext, 0.8)}; }
.datemenu-popover .message .message-header .message-header-content .event-time,
.notification-banner .message-header .message-header-content .event-time { color: ${rgba(ptext, 0.65)}; }
.notification-banner { box-shadow: ${shadow('0 6px 18px 0 rgba(0,0,0,0.25)')}; }
/* Neutral secondary controls, including notification actions and Do Not Disturb. */
.quick-settings .icon-button,
.datemenu-popover .button,
.notification-banner .notification-button { background-color: ${lift(pop, 32)}; color: ${ptext}; }
.quick-settings .icon-button:hover,
.datemenu-popover .button:hover,
.notification-banner .notification-button:hover { background-color: ${lift(pop, 49)}; }
.datemenu-popover .toggle-switch:checked { background-color: ${rgba(accent, 0.6)}; }
`;
}
