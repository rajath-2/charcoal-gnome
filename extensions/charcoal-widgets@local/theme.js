// Builds the widget stylesheet from preferences. Pure: also imported by tests.
const hexRgb = hex => /^#[0-9a-f]{6}$/i.test(hex)
    ? [1, 3, 5].map(i => parseInt(hex.slice(i, i + 2), 16)) : [128, 128, 128];
const hex = value => /^#[0-9a-f]{6}$/i.test(value) ? value : '#808080';
const rgba = (value, alpha) => `rgba(${hexRgb(value).join(',')},${+alpha.toFixed(3)})`;
export const WIDGET_NAMES = ['weather', 'calendar', 'music'];

// One block per widget, every length scaled by that widget's size preference.
export function buildCss(o) {
    const text = hex(o['text-color']), accent = hex(o['accent-color']);
    const background = hex(o['background-color']);
    const dim = rgba(text, 0.6);
    const blocks = WIDGET_NAMES.map(name => {
        const s = (o[`${name}-size`] ?? 100) / 100;
        const px = n => `${Math.max(n > 0 ? 1 : 0, Math.round(n * s))}px`;
        const pt = n => `${+(n * s).toFixed(1)}pt`;
        const w = `.charcoal-widget-${name}`;
        const border = o['border-width'] > 0
            ? `${px(o['border-width'])} solid ${rgba(o['border-color'], o['border-opacity'] / 100)}` : 'none';
        const shadow = o['shadow-size'] > 0
            ? `0 0 ${px(o['shadow-size'])} ${rgba(o['shadow-color'], o['shadow-opacity'] / 100)}` : 'none';
        return `/* ${name} */
${w} {
    background-color: ${rgba(background, o['background-opacity'] / 100)};
    border: ${border};
    border-radius: ${px(o['corner-radius'])};
    box-shadow: ${shadow};
    color: ${text};
    padding: ${px(16)};
    font-size: ${pt(10.5)};
}
${w} .charcoal-widget-dim { color: ${dim}; }
${w} .charcoal-widget-accent { color: ${accent}; }
${w} .charcoal-widget-title { font-weight: 600; font-size: ${pt(13)}; }
${w} .charcoal-widget-big { font-size: ${pt(30)}; font-weight: 300; }
${w} .charcoal-cal-header { font-weight: 600; }
${w} .charcoal-cal-nav { color: ${text}; padding: ${px(2)} ${px(8)}; border-radius: ${px(8)}; }
${w} .charcoal-cal-nav:hover { background-color: ${rgba(text, 0.1)}; }
${w} .charcoal-cal-weekday { color: ${dim}; font-size: ${pt(9)}; text-align: center; }
${w} .charcoal-cal-day {
    color: ${text}; font-size: ${pt(10)}; width: ${px(30)}; height: ${px(28)};
    border-radius: ${px(14)}; border: 1px solid transparent; padding: 0;
}
${w} .charcoal-cal-day:hover { background-color: ${rgba(text, 0.1)}; }
${w} .charcoal-cal-other { color: ${rgba(text, 0.3)}; }
${w} .charcoal-cal-today { background-color: ${accent}; color: ${background}; font-weight: 600; }
${w} .charcoal-cal-today:hover { background-color: ${accent}; }
${w} .charcoal-cal-selected { border: 1px solid ${accent}; }
${w} .charcoal-cal-dot { background-color: ${accent}; width: ${px(3)}; height: ${px(3)}; border-radius: ${px(2)}; }
${w} .charcoal-cal-today .charcoal-cal-dot { background-color: ${background}; }
${w} .charcoal-cal-event { font-size: ${pt(9)}; }
${w} .charcoal-seek-trough { background-color: ${rgba(text, 0.18)}; height: ${px(4)}; border-radius: ${px(2)}; }
${w} .charcoal-seek-fill { background-color: ${accent}; height: ${px(4)}; border-radius: ${px(2)}; }
${w} .charcoal-seek-time { color: ${dim}; font-size: ${pt(9)}; }
${w} .charcoal-music-button { color: ${text}; padding: ${px(6)}; border-radius: 99px; }
${w} .charcoal-music-button:hover { background-color: ${rgba(text, 0.1)}; }
${w} .charcoal-music-button:insensitive { color: ${rgba(text, 0.35)}; }
${w} .charcoal-music-button.active { color: ${accent}; }
${w} .charcoal-play-ring { border: ${px(2)} solid ${accent}; color: ${accent}; padding: ${px(10)}; border-radius: 99px; }
${w} .charcoal-artwork { width: ${px(72)}; height: ${px(72)}; border-radius: ${px(10)}; background-size: cover; }
/* end */`;
    });
    return `/* Generated by Charcoal Widgets from its preferences. */\n${blocks.join('\n')}\n`;
}
