// Builds the widget stylesheet from preferences. Pure: also imported by tests.
const hexRgb = hex => /^#[0-9a-f]{6}$/i.test(hex)
    ? [1, 3, 5].map(i => parseInt(hex.slice(i, i + 2), 16)) : [128, 128, 128];
const hex = value => /^#[0-9a-f]{6}$/i.test(value) ? value : '#808080';
const rgba = (value, alpha) => `rgba(${hexRgb(value).join(',')},${+alpha.toFixed(3)})`;

export function buildCss(o) {
    const text = hex(o['text-color']), accent = hex(o['accent-color']);
    const background = hex(o['background-color']);
    const border = o['border-width'] > 0
        ? `${o['border-width']}px solid ${rgba(o['border-color'], o['border-opacity'] / 100)}` : 'none';
    const shadow = o['shadow-size'] > 0
        ? `0 0 ${o['shadow-size']}px ${rgba(o['shadow-color'], o['shadow-opacity'] / 100)}` : 'none';
    const dim = rgba(text, 0.6);
    return `/* Generated by Charcoal Widgets from its preferences. */
.charcoal-widget {
    background-color: ${rgba(background, o['background-opacity'] / 100)};
    border: ${border};
    border-radius: ${o['corner-radius']}px;
    box-shadow: ${shadow};
    color: ${text};
    padding: 16px;
}
.charcoal-widget-dim { color: ${dim}; }
.charcoal-widget-accent { color: ${accent}; }
.charcoal-widget-title { font-weight: 600; font-size: 13pt; }
.charcoal-widget-big { font-size: 30pt; font-weight: 300; }
.charcoal-cal-header { font-weight: 600; }
.charcoal-cal-nav { color: ${text}; padding: 2px 8px; border-radius: 8px; }
.charcoal-cal-nav:hover { background-color: ${rgba(text, 0.1)}; }
.charcoal-cal-weekday { color: ${dim}; font-size: 9pt; text-align: center; }
.charcoal-cal-day {
    color: ${text}; font-size: 10pt; width: 30px; height: 28px;
    border-radius: 14px; border: 1px solid transparent; padding: 0;
}
.charcoal-cal-day:hover { background-color: ${rgba(text, 0.1)}; }
.charcoal-cal-other { color: ${rgba(text, 0.3)}; }
.charcoal-cal-today { background-color: ${accent}; color: ${background}; font-weight: 600; }
.charcoal-cal-today:hover { background-color: ${accent}; }
.charcoal-cal-selected { border: 1px solid ${accent}; }
.charcoal-cal-dot { background-color: ${accent}; width: 3px; height: 3px; border-radius: 2px; }
.charcoal-cal-today .charcoal-cal-dot { background-color: ${background}; }
.charcoal-cal-event { font-size: 9pt; }
.charcoal-seek-trough { background-color: ${rgba(text, 0.18)}; height: 4px; border-radius: 2px; }
.charcoal-seek-fill { background-color: ${accent}; height: 4px; border-radius: 2px; }
.charcoal-seek-time { color: ${dim}; font-size: 9pt; }
.charcoal-music-button { color: ${text}; padding: 6px; border-radius: 99px; }
.charcoal-music-button:hover { background-color: ${rgba(text, 0.1)}; }
.charcoal-music-button:insensitive { color: ${rgba(text, 0.35)}; }
.charcoal-music-button.active { color: ${accent}; }
.charcoal-play-ring { border: 2px solid ${accent}; color: ${accent}; padding: 10px; border-radius: 99px; }
.charcoal-artwork { border-radius: 10px; }
`;
}
